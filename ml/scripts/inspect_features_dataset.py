"""
inspect_features_dataset.py

Purpose:
    Verify the feature engineered dataset generated by features.py.
"""

from pathlib import Path

import polars as pl

# ---------------------------------------------------------------------
# Project Paths
# ---------------------------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent

FEATURE_DATA_FILE = (
    BASE_DIR
    / "data"
    / "processed"
    / "saferoute_features.parquet"
)

# ---------------------------------------------------------------------
# Load Dataset
# ---------------------------------------------------------------------

print("=" * 70)
print("Loading Feature Engineered Dataset")
print("=" * 70)

df = pl.read_parquet(FEATURE_DATA_FILE)

# ---------------------------------------------------------------------
# Dataset Shape
# ---------------------------------------------------------------------

print("\nDataset Shape")
print("-" * 70)

print(f"Rows    : {df.height:,}")
print(f"Columns : {df.width}")

# ---------------------------------------------------------------------
# Schema
# ---------------------------------------------------------------------

print("\nSchema")
print("-" * 70)

print(df.schema)

# ---------------------------------------------------------------------
# Missing Values
# ---------------------------------------------------------------------

print("\nMissing Values")
print("-" * 70)

print(df.null_count())

# ---------------------------------------------------------------------
# First Five Records
# ---------------------------------------------------------------------

print("\nFirst Five Records")
print("-" * 70)

print(df.head())

# ---------------------------------------------------------------------
# Statistical Summary
# ---------------------------------------------------------------------

print("\nStatistical Summary")
print("-" * 70)

print(df.describe())

# ---------------------------------------------------------------------
# Weather Category Distribution
# ---------------------------------------------------------------------

print("\nWeather Category Distribution")
print("-" * 70)

weather_distribution = (
    df
    .group_by("Weather_Category")
    .len(name="Count")
    .sort("Count", descending=True)
)

print(weather_distribution)

# ---------------------------------------------------------------------
# Rush Hour Distribution
# ---------------------------------------------------------------------

print("\nRush Hour Distribution")
print("-" * 70)

rush_distribution = (
    df
    .group_by("IsRushHour")
    .len(name="Count")
)

print(rush_distribution)

# ---------------------------------------------------------------------
# Day / Night Distribution
# ---------------------------------------------------------------------

print("\nDay / Night Distribution")
print("-" * 70)

night_distribution = (
    df
    .group_by("IsNight")
    .len(name="Count")
)

print(night_distribution)

# ---------------------------------------------------------------------
# Road Infrastructure Distribution
# ---------------------------------------------------------------------

print("\nNear Road Infrastructure Distribution")
print("-" * 70)

road_distribution = (
    df
    .group_by("NearRoadInfrastructure")
    .len(name="Count")
)

print(road_distribution)

# ---------------------------------------------------------------------
# Low Visibility Distribution
# ---------------------------------------------------------------------

print("\nLow Visibility Distribution")
print("-" * 70)

visibility_distribution = (
    df
    .group_by("LowVisibility")
    .len(name="Count")
)

print(visibility_distribution)

# ---------------------------------------------------------------------
# Precipitation Distribution
# ---------------------------------------------------------------------

print("\nPrecipitation Distribution")
print("-" * 70)

precipitation_distribution = (
    df
    .group_by("HasPrecipitation")
    .len(name="Count")
)

print(precipitation_distribution)

# ---------------------------------------------------------------------
# Target Variable Distribution
# ---------------------------------------------------------------------

print("\nSeverity Distribution")
print("-" * 70)

severity_distribution = (
    df
    .group_by("Severity")
    .len(name="Count")
    .sort("Severity")
)

print(severity_distribution)

print("\n" + "=" * 70)
print("Feature Dataset Validation Completed Successfully!")
print("=" * 70)